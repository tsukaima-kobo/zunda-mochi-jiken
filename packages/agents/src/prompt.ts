/**
 * 票の数（パワープレイ）。人狼側（人狼＋狂信者）の票が、半分・過半数に届いているかを伝える。人狼と狂信者には毎回、従業員と占い師には届いた時だけ。
 * 人数は、全員に公開された情報（出席者・クビで分かった人狼の数・顔ぶれ）だけから数える。狂信者が起きているかどうかは公開されないので、「起きていれば」と書く。
 */
function voteMathLines(obs: MeetingObservation): string[] {
  const cast = obs.cast;
  const role = obs.self.role;
  if (!cast || cast.madmen <= 0 || role === 'fox') return [];
  const awake = obs.stakes?.awake ?? obs.meeting.attendees.length;
  const fairies = obs.stakes?.fairiesLeft ?? cast.nibblers;
  if (fairies <= 0 || awake <= 0) return [];
  const side = fairies + cast.madmen;
  const sure = Math.floor(awake / 2) + 1;
  const level = side >= sure ? 'over' : side * 2 === awake ? 'half' : 'under';
  const foxUp = (cast.foxes ?? 0) > (obs.foxesOut ?? 0);
  const head = `【票の数】集会に出ているのは${awake}人。${sure}票そろえば、ほかの人がどう入れても、その相手を必ずクビにできます。`;
  const others = 'ほかの全員が、同じ1人かスキップに票をそろえないかぎり';
  if (role === 'nibbler') {
    const mine = `${head}あなたたち人狼は${fairies}票。狂信者が起きていて票を合わせてくれれば、${side}票です。`;
    const tell = '狂信者は、あなたたちが人狼だと知っているので、あなたたちが票を入れる相手に合わせてきます。誰に入れるかを、集会の話の中ではっきり言っておくと、票がそろいます（狂信者らしい人が出席していない時は、票が足りません）。';
    const fox = foxUp ? 'この票は、まず妖狐に使います（妖狐が誰か分かっている時）。妖狐には杖が効かず、クビにさせるしかないからです。' : '';
    if (level === 'over') return [`${mine}いまは、狂信者と票をそろえれば、あなたたちだけで誰でもクビにできる人数です（パワープレイ）。${tell}票がそろえば、人狼だと名乗っても、あなたたちはクビになりません。${fox}`];
    if (level === 'half') return [`${mine}ちょうど半分の票です。${others}、あなたたちの票が通ります（同じ数で並んだ時は、誰もクビになりません）。${tell}${fox}`];
    return [`${mine}まだ半分に届かないので、いま人狼だと名乗り出ると、あなたたちがクビになります。`];
  }
  if (role === 'madman') {
    const mine = `${head}人狼は${fairies}人残っているので、あなたの票と合わせて、人狼側は${side}票です。`;
    const follow = '人狼（【あなたが知っている人狼】）が集会で疑いを向けている相手や、入れると言った相手に、票を合わせてください。人狼は、誰が狂信者かを知りません。あなたから狂信者だと名乗り出て、誰に入れるか言ってほしいと人狼に呼びかける手もあります。';
    const fox = foxUp ? '妖狐が起きている試合では、この票は、まず妖狐に使います（妖狐は人狼の杖では止められず、クビにさせるしかないからです）。' : '';
    if (level === 'over') return [`${mine}いまは、人狼と票をそろえれば、人狼側だけで誰でもクビにできる人数です（パワープレイ）。${follow}${fox}`];
    if (level === 'half') return [`${mine}ちょうど半分の票です。${others}、人狼側の票が通ります。${follow}${fox}`];
    return [`${mine}まだ半分に届きません。人狼には票を入れず、人狼が疑いを向けている相手に票を合わせると、人狼の助けになります。`];
  }
  if (level === 'under') return [];
  const theirs = `${head}人狼は${fairies}人残っていて、狂信者が起きていれば、人狼側は${side}票です。`;
  if (level === 'over') return [`${theirs}人狼側が票をそろえると、多数決では止められない人数です。あなたたちの票は、割らずに1人にそろえてください。票で勝てない時は、仕込みを終わらせて勝つ道も残っています。`];
  return [`${theirs}人狼側が票をそろえてきたら、あなたたちの票が1つでも割れると、相手の票が通ります。誰に入れるかを、話し合いでそろえてください。`];
}

/** 本人が知っている人狼の名前。人狼には仲間の人狼、狂信者には人狼。 */
function allyLines(self: MeetingObservation['self'] | RoamObservation['self']): string[] {
  if (self.role === 'nibbler') return [`【仲間の人狼】${self.allies.length > 0 ? self.allies.join('、') : 'いない（あなただけ）'}`];
  if (self.role === 'madman' && self.allies.length > 0) return [`【あなたが知っている人狼】${self.allies.join('、')}（人狼は、あなたが狂信者だとは知りません）`];
  return [];
}

function selfLines(self: MeetingObservation['self'], guide: Record<Role, string>, cast?: Cast | null, foxesOut = 0): string[] {
  const foxWork = self.role === 'fox' && self.foxWork ? self.foxWork : null;
  const lines = [...whoLines(self), (foxWork ? (guide === ROAM_GUIDE ? FOX_WORK_ROAM : FOX_WORK_MEETING) : guide[self.role]).replaceAll('{liars}', liarsOf(cast))];
  lines.push(...allyLines(self));
  if (cast) lines.push(...castLines(cast));
  lines.push(...winRouteLines(self.role, cast, foxesOut));
  // 妖狐がいる試合: 妖狐をクビにしないと、自分たちも負ける（妖狐本人には出さない）
  const threat = (cast?.foxes ?? 0) > foxesOut ? FOX_THREAT[self.role] : '';
  if (threat) lines.push(threat.replace('{steps}', (cast?.foxSteps ?? 0) > 0 ? `、しかも妖狐が自分の仕込みを${cast?.foxSteps}工程終えていれば` : ''));
  // 占い師がいる試合だけ: 役ごとの一言（占い師のいない試合の指示は、前と同じ文のまま）
  const tip = (cast?.seers ?? 0) > 0 ? (guide === ROAM_GUIDE ? SEER_ROAM_TIPS : SEER_MEETING_TIPS)[self.role] : '';
  if (tip) lines.push(tip.replaceAll('{liars}', liarsOf(cast)).replaceAll('{hold}', (cast?.divineSeconds ?? 0) > 0 ? `${cast?.divineSeconds}秒` : 'しばらく'));
  lines.push(...madmanAllyLines(self, cast, foxesOut));
  if (guide === MEETING_GUIDE) lines.push(...foxHuntLines(self, cast, foxesOut));
  // 妖狐がいる試合の見回り: かまどの焚きすぎで人間が2か所に分かれた時は、ひとりになった人を餅にしやすい（2026-11-21 夕。【妖狐を明かす時】の続き）
  if (guide === ROAM_GUIDE && self.role === 'nibbler' && (cast?.foxes ?? 0) > foxesOut) {
    // 集会のあと、妨害は15秒、杖の力は25秒で使えるようになるので、力がもうすぐ使える時に焚きすぎにすると、直る前に餅にできた（20秒: 40回中26回、23秒: 31回）
    // 同じ日の夜、直す場所の「井戸の水」（中庭、鐘から6升）を「氷」（氷室、鐘から46升・かまどの火から71升）へ移したあとの試算: 直るまで中央値 5.4〜8.0秒・最大 約20秒。直る前に餅にできたのは 15秒: 12回、20秒: 29回、23秒: 34回（40回中）
    lines.push('【かまどの焚きすぎ】かまどを焚きすぎにすると、人間たちは直す場所の2か所に分かれて走ります。その間は、ひとりになった人をずんだ餅にしやすい時です。ただし、直す場所に人が着くと、数秒で直ってしまいます。焚きすぎにするのは、杖の力がもうすぐ使える時（あと5秒以内）にして、遠い方の直す場所へ向かう人のそばにいてください。あと1人餅にすれば勝てる人数の時に、とくに使えます（妖狐が起きていると横取りされるので、先に妖狐をクビにさせてから）。');
  }
  if (self.role === 'seer') lines.push(...divinedLines(self.divined ?? []));
  if (foxWork) lines.push(`【妖狐の仕込みの進み】${foxWork.done}工程 終えた（横取りに要るのは ${foxWork.need}工程。${foxWork.done >= foxWork.need ? 'もう足りている' : `あと ${foxWork.need - foxWork.done}工程`}）`);
  return lines;
}

