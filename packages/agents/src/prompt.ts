function resignLines(obs: MeetingObservation): string[] {
  const awake = obs.stakes?.awake ?? obs.meeting.attendees.length;
  if (awake > RESIGN_MEETING_AWAKE) return [];
  const foxUp = !!obs.cast && (obs.cast.foxes ?? 0) > (obs.foxesOut ?? 0);
  return [resignGuide(foxUp, '集会')];
}

