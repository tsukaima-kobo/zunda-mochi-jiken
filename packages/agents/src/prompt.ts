/**
 * この試合の顔ぶれ（人数）と、狐・占い師がいる試合の決まり。全員に同じ文を渡す（誰がどの役かは入らない）。
 * 占い師の決まりと、占われた狐の決まりは、占い師がいる試合にだけ書く（いない試合の指示は、前と同じ文のまま）。
 */
/** 占い師を名乗って嘘をつけるのは誰か（この試合にいる役だけ）。「妖精や妖精マニアや狐」など。 */
function liarsOf(cast?: Cast | null): string {
  return ['妖精', ...((cast?.madmen ?? 0) > 0 ? ['妖精マニア'] : []), ...((cast?.foxes ?? 0) > 0 ? ['狐'] : [])].join('や');
}

export function castLines(cast: Cast): string[] {
  const foxes = cast.foxes ?? 0;
  const seers = cast.seers ?? 0;
  const madmen = cast.madmen > 0 ? `・妖精マニア ${cast.madmen}人` : '';
  const fox = foxes > 0 ? `・狐 ${foxes}人` : '';
  const seer = seers > 0 ? `・占い師 ${seers}人` : '';
  const lines = [`【この試合の顔ぶれ】${cast.total}人（ずんだの妖精 ${cast.nibblers}人${madmen}${fox}${seer}・従業員 ${cast.total - cast.nibblers - cast.madmen - foxes - seers}人）`];
  // 議論に狐を吊らないと自分たちも負けてしまうというゲーム仕様をAIに理解してもらってください。」
  if (foxes > 0) {
    const steps = cast.foxSteps ?? 0;
    lines.push(
      `【狐の決まり】狐は、ひとりだけの陣営です。試合が終わった時（従業員と妖精のどちらが勝っても）、狐が起きていて${steps > 0 ? `、しかも自分の仕込みを${steps}工程以上終えていれば` : 'いれば'}、狐が勝ちを横取りし、従業員も妖精も負けになります${steps > 0 ? '（仕込みが足りなければ、起きていても横取りできません。狐の仕込みは、従業員の仕込みの進み具合には入りません）' : ''}。狐は、妖精に手をかざされても、ずんだ餅になりません（手が効かなかったことは、手をかざした妖精にだけ分かります。狐本人にも、そばで見ていた人にも分かりません）。狐を止める方法は、集会でクビにするか、占い師が占うかだけです。クビになった人が狐なら、「狐だった」と全員に知らされます。`,
    );
  }
  if (seers === 0) return lines;
  lines.push(
    '【占い師の決まり】占い師は、従業員の側の人間です（従業員と同じに仕込みを進め、従業員が勝てば勝ち）。見回り1回につき1人、相手のそばに{hold}いつづけて占い、その相手がずんだの妖精かどうかを知ることができます（見回りのたびに、また1人占えます）。占ったことは、相手にも周りにも分かりません。結果を知っているのは占い師だけで、集会で言うかどうかは本人が決めます。誰が占い師かは、本人しか知りません。そのため、{liars}が占い師を名乗って、嘘の結果を言うこともできます。占い師を名乗る人がいたら、いつ・どこで・誰を占ったかの話が、ほかの人の見たことと合うかを確かめてください。クビになった時に知らされるのは、{told}だけです（占い師だったかどうかは知らされません）。'
      .replaceAll('{liars}', liarsOf(cast))
      .replace('{hold}', (cast.divineSeconds ?? 0) > 0 ? `${cast.divineSeconds}秒（途中で離れると、はじめから）` : 'しばらく')
      .replace('{told}', foxes > 0 ? '「妖精だったかどうか」と、狐なら「狐だった」こと' : '「妖精だったかどうか」'),
  );
  if (foxes > 0) {
    lines.push(
      '【狐と占い】狐は、妖精の手ではずんだ餅になりませんが、占い師に占われると、その場でずんだ餅に変わります（占いの結果は「妖精ではなかった」と出ます）。誰も手をかざしていないのに人が急にずんだ餅に変わったら、それは占われた狐です（すぐそばに、占い師がいたはずです）。',
    );
  }
  return lines;
}

/** 占い師本人にだけ渡す、これまでの占いの結果。 */
function divinedLines(divined: readonly Divined[]): string[] {
  if (divined.length === 0) return ['【あなたの占いの結果】まだ誰も占っていない（占えるのは、見回り1回につき1人）'];
  return [
    '【あなたの占いの結果】（あなただけが知っている、本当のこと）',
    ...divined.map((d) => `- ${d.round}回目の見回り: ${d.name} → ${d.fairy ? '妖精だった' : d.cursed ? '妖精ではなかった（占ったとたんに、ずんだ餅に変わった。狐だった）' : '妖精ではなかった'}`),
  ];
}

type Cast = NonNullable<RoamObservation['cast']>;

const absences = (list: readonly Absence[]) => list.map((a) => `${a.name}（${ABSENCE_LABEL[a.status]}）`).join('、');

/** これまでの経過。全員に公開された集会の結果と、本人の覚え書き。 */
function backgroundLines(history: readonly string[], memory: PromptMemory): string[] {
  const lines: string[] = [];
  if (history.length > 0) lines.push('【これまでの集会】', ...history.map((line) => `- ${line}`));
  if (memory.past.length > 0) lines.push('【前の回までの、あなたの記憶】', ...memory.past.map((line) => `- ${line}`));
  return lines;
}

