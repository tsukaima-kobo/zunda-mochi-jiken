const waitText = (seconds: number, ready: string) => (seconds > 0 ? `あと ${seconds} 秒` : ready);

/** 仕込み・困りごと・鐘など。観測に無い項目は出さない。役職で変わる項目は、本人の観測にある時だけ出る。 */
function workLines(obs: RoamObservation): string[] {
  const lines: string[] = [];
  const { trouble } = obs;
  if (obs.duties && obs.duties.length > 0) {
    // 横取りに仕込みの条件がある試合の狐は、仕込みが本物（自分の条件のぶん）。2026-11-21 まで、見出しが「見せかけ」のままで、狐への指示と食い違っていた
    const foxWork = obs.self.role === 'fox' && obs.self.foxWork;
    lines.push(obs.self.role === 'artisan' || obs.self.role === 'seer' ? '【あなたの仕込み】' : foxWork ? '【あなたの仕込み（狐の横取りの条件のぶん。従業員みんなの進み具合には入らない）】' : '【あなたの仕込み（ふりをするための見せかけ）】');
    // 本家のように、何か所も回る仕込みは、いまの工程を終えると次の場所が分かる（2026-11-21 から）
    if (obs.duties.some((duty) => (duty.total ?? duty.steps.length) > 1)) lines.push('（何か所も回る仕込みは、いまの場所を終えると、次の場所が分かります）');
    if (obs.dutiesWaiting !== undefined) lines.push(obs.dutiesWaiting > 0 ? `（仕込みを1つ終えると、次の仕込みが1つ出ます。まだ出ていない仕込み: ${obs.dutiesWaiting}個）` : '（まだ出ていない仕込みは、もうありません）');
    for (const duty of obs.duties) {
      const total = duty.total ?? duty.steps.length;
      const done = duty.steps.filter((step) => step.done).length;
      const now = duty.steps.find((step) => !step.done);
      if (!now) lines.push(`- ${duty.name}（終わった）`);
      // 1工程だけの仕込みは、名前と持ち場の名前が同じことが多いので、同じ言葉を2回書かない
      else if (total === 1) lines.push(now.what === duty.name ? `- ${duty.name}（${now.room}）` : `- ${duty.name}: ${now.what}（${now.room}）`);
      else lines.push(`- ${duty.name}（${total}工程のうち ${done}工程 済）: 次は ${now.what}（${now.room}）`);
    }
  }
  if (trouble) {
    const held = (isHeld: boolean) => (trouble.kind === 'crisis' ? (isHeld ? '（誰かがついている）' : '（まだ誰もついていない）') : '');
    const places = trouble.fixAt.map((f) => `${f.room} の「${f.name}」${held(f.held)}`).join('、');
    lines.push(
      trouble.kind === 'lights'
        ? `【困りごと】工房のあかりが消えている。直す場所: ${places}`
        : `【困りごと】かまどが焚かれすぎている。あと ${trouble.secondsLeft} 秒。直す場所（全部に同時に人がつくと直る）: ${places}`,
    );
  }
  if (obs.shutRooms && obs.shutRooms.length > 0) lines.push(`【戸】戸が閉まっている: ${obs.shutRooms.join('、')}（しばらくすると開く）`);
  if (obs.bell) {
    const bell =
      obs.bell.usesLeft <= 0
        ? 'あなたは、もう鳴らせない'
        : trouble
          ? '困りごとが片づくまで、鳴らせない'
          : obs.bell.waitSeconds > 0
            ? `あと ${obs.bell.waitSeconds} 秒は鳴らせない`
            : `いま鳴らしに行ける（あなたはあと${obs.bell.usesLeft}回）`;
    lines.push(`【中庭の鐘】${bell}`);
  }
  if (obs.devices && obs.devices.length > 0) {
    lines.push(`【工房の道具】${obs.devices.map((d) => `${d.room}の「${d.name}」: ${DEVICE_HELP[d.kind]}`).join(' / ')}`);
  }
  if (obs.cameraView) {
    const views = obs.cameraView.map((view) => `${view.place}: ${view.seen.length > 0 ? view.seen.map((s) => `${s.name}${s.asleep ? '（ずんだ餅になっている）' : ''}`).join('、') : '誰も映っていない'}`);
    lines.push(`【いま防犯カメラの画面に映っているもの】${views.join(' / ')}`);
  }
  if (obs.cameraLit && obs.cameraLit.length > 0) {
    const screen = obs.devices?.find((d) => d.kind === 'cameras');
    lines.push(`【防犯カメラ】${obs.cameraLit.join('、')}のカメラに、赤いランプがついている（いま誰かが${screen ? `、${screen.room}の画面で` : ''}カメラを見ている）`);
  }
  if (obs.napCooldown !== null) {
    lines.push(`【ずんだ餅に変える力】${obs.napCooldown > 0 ? `あと ${obs.napCooldown} 秒で使えるようになる` : 'いま使える'}`);
  }
  if (obs.divine) {
    lines.push(`【占い】${obs.divine.usesLeft > 0 ? 'この見回りでは、まだ占っていない。1人を占える（見えている相手を選ぶ）' : 'この見回りでは、もう占った（次の見回りで、また1人占える）'}`);
  }
  if (obs.sabotage) {
    const main = trouble ? 'いまの困りごとが片づくまで、できない' : waitText(obs.sabotage.waitSeconds, 'いまできる');
    const doors = waitText(obs.sabotage.doorWaitSeconds, 'いま閉められる');
    lines.push(`【妨害】${SABOTAGE_LIGHTS}・${SABOTAGE_CRISIS}: ${main} / 戸: ${doors}（閉められる部屋: ${obs.sabotage.doorRooms.join('、')}）`);
  }
  if (obs.hatches && obs.hatches.length > 0) {
    lines.push(`【床下の抜け道】同じ組の部屋どうしがつながっている: ${obs.hatches.map((g) => `${g.group}（${g.rooms.join('・')}）`).join(' / ')}`);
  }
  return lines;
}

/**
 * 人数は、名簿と「もう工房にいない人」（集会で全員に分かったこと）と、仲間の妖精から数える。まだ見つかっていない餅は起きている数に入るので、多めに数える側にずれる（出すべき時に出さないことはあっても、勝てない時に出すことはない）。
 * 狐が起きている試合では出さない（人数で勝っても、狐に横取りされることがある。【狐を明かす時】の方で伝える）。
 */
function lastNapLines(obs: RoamObservation): string[] {
  if (obs.self.role !== 'nibbler' || (obs.cast?.foxes ?? 0) > (obs.foxesOut ?? 0)) return [];
  const away = new Set(obs.away.map((a) => a.name));
  const awake = obs.roster.filter((name) => !away.has(name)).length;
  const fairies = 1 + obs.self.allies.filter((name) => !away.has(name)).length;
  const humans = awake - fairies;
  if (humans <= 0 || humans - 1 > fairies) return [];
  return [
    `【あと1人で勝ち】起きている人間は、あと${humans}人です（ずんだの妖精は${fairies}人）。あと1人ずんだ餅にすれば、その場で、あなたたちの勝ちです。見られていても、かまいません（餅にした時点で試合が終わるので、集会はありません）。手をかざす力が使えるようになったら、すぐ、そばの人に transform してください（力が使えるようになる前に選んでおくと、使えるようになった瞬間に手をかざします）。従業員は、鐘を鳴らして集会に逃げようとします。鐘は、困りごとの間は鳴らせません。集会のあとは、妨害が使えるようになったらすぐ、「${SABOTAGE_CRISIS}」か「${SABOTAGE_LIGHTS}」で鐘を止めて、直しに行く人についていってください。`,
  ];
}

/** 歩き回っている間に、次の行動を決めるためのプロンプト。 */
export function renderRoamUser(obs: RoamObservation, feedback?: string, memory: PromptMemory = NO_MEMORY): string {
  const lines = selfLines(obs.self, ROAM_GUIDE, obs.cast, obs.foxesOut);
  lines.push(...lastNapLines(obs));
  const bar = obs.taskBar
    ? `工房全体の仕込みの進み具合は ${obs.taskBar.done}/${obs.taskBar.total}。`
    : 'この工房に仕込みは無く、開店の時刻まで工房を守りきれば従業員の勝ち。';
  // 仕込みのある工房には、開店の時刻（制限時間）は無い
  const opening = obs.taskBar ? '' : `開店まであと ${obs.secondsUntilOpening} 秒。`;
  lines.push(`【いま】${obs.round}回目の見回り。開始から ${clockLabel(obs.clock)}。${opening}${bar}`);
  if (obs.away.length > 0) lines.push(`【もう工房にいない人】${absences(obs.away)}`);
  lines.push(...backgroundLines(obs.history, memory));
  lines.push(`【場所】あなたは ${obs.where} にいる。`);
  const seen = obs.visible.map((v) => `${v.name}（${v.where}${v.asleep ? '・ずんだ餅になっている' : v.working ? '・持ち場で手を動かしている' : v.checking ? `・「${v.checking}」を見ている` : ''}）`);
  lines.push(`【見えている相手】${seen.length > 0 ? seen.join('、') : 'いない'}`);
  if (obs.events.length > 0) lines.push(`【いま目の前で起きたこと】${obs.events.join(' / ')}`);
  const voices = (obs.heard ?? []).filter((h) => h.speaker !== obs.self.name);
  if (voices.length > 0) lines.push(`【いま聞こえた声】${voices.map((h) => `${h.speaker}（${h.where ?? '姿は見えない'}）「${h.text}」`).join(' / ')}`);
  lines.push(`【していること】${obs.activity}`);
  if (obs.lastResult) lines.push(`【直前の結果】${obs.lastResult}`);
  lines.push(...workLines(obs));
  lines.push('【今回の見回りで見聞きしたこと】');
  lines.push(...(memory.recent.length > 0 ? memory.recent.map((line) => `- ${line}`) : ['- （まだ何もない）']));
  if (memory.talk && memory.talk.length > 0) lines.push('【今回の見回りで、そばで交わされた言葉】', ...memory.talk.map((line) => `- ${line}`));
  lines.push(`【工房の間取り】端から端まで歩いて約${obs.crossSeconds}秒。場所と、そこから歩いて移れる隣の場所:`);
  lines.push(...obs.layout.map((line) => `- ${line}`));
  lines.push(`【行き先にできる場所】${obs.rooms.join(' / ')}（離れた場所を選んでも、道はひとりでに選ばれます）`);
  lines.push(`【選べる行動】${roamActions(obs).map((a) => ACTION_HELP[a]).join(' / ')}`);
  if (obs.chatWaitSeconds !== undefined) {
    lines.push(`${VOICE_GUIDE}${VOICE_TIPS[obs.self.role]}`);
    if (obs.round >= 2) lines.push(`${SUSPECT_GUIDE}${SUSPECT_TIPS[obs.self.role]}`);
    if (obs.chatWaitSeconds > 0) lines.push(`（さっき話したばかりなので、あと ${obs.chatWaitSeconds} 秒は話せません。say は空にしてください）`);
  }
  if (feedback) lines.push(`【やり直し】前の返答は受け付けられませんでした。${feedback}`);
  return lines.join('\n');
}
